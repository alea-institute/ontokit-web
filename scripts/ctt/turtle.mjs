// CTT taxonomy import: snapshot -> OWL/Turtle module, and merge into a host ontology.
//
// OntoKit browses OWL classes, so every CTT word becomes an owl:Class under one
// "CTT term" root (false friends and core words get their own subclasses), and the 24
// communities become named individuals. Every term carries its calibration status and a
// link back to its public vocabulary entry. The module declares no owl:Ontology, so
// merging it into the Catholic ontology leaves that ontology's own header in charge.
import { validateSnapshot } from './snapshot.mjs';

// Pending a naming decision (docs/handoffs/2026-10-20-sweep-cloud-ontokit-web.md).
export const DEFAULT_BASE = 'https://ontology.catholicos.catholic/ctt/';
export const CTT_PREFIX = 'ctt';
const RDF_PREFIXES = {
  owl: 'http://www.w3.org/2002/07/owl#',
  rdfs: 'http://www.w3.org/2000/01/rdf-schema#',
  skos: 'http://www.w3.org/2004/02/skos/core#',
  dcterms: 'http://purl.org/dc/terms/',
  xsd: 'http://www.w3.org/2001/XMLSchema#',
};

/** Turtle string literal with the mandatory escapes. */
export const literal = (value, lang = 'en') => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"${lang ? `@${lang}` : ''}`;
const integer = value => `"${value}"^^xsd:nonNegativeInteger`;
const iri = value => `<${value}>`;

function assertBase(base) {
  let url;
  try { url = new URL(base); } catch { throw new Error('CTT base must be an absolute IRI'); }
  if (!['https:', 'http:'].includes(url.protocol) || !/[/#]$/.test(base) || /[\s<>"{}|\\^`]/.test(base)) throw new Error('CTT base must be an http(s) IRI ending in / or #');
  return base;
}

const ANNOTATIONS = [
  ['calibrationStatus', 'calibration status', 'Whether the CTT verdicts behind this entry have been checked against human judgment.'],
  ['verdict', 'CTT verdict', 'How the CTT atlas classifies the word: one-sense, multi-sense, false-friend or no-verdict.'],
  ['senseCount', 'sense count', 'Number of senses the CTT atlas distinguishes for the word.'],
  ['communityCount', 'community count', 'Number of communities in which the CTT atlas measured the word.'],
  ['useCount', 'use count', 'Number of measured uses of the word in the CTT corpus.'],
  ['falseFriendPairCount', 'false-friend pair count', 'Number of community pairs that mainly use the word in different senses.'],
  ['senseSubstitutes', 'sense substitutes', 'A sense, named by the words a language model most often puts in its place.'],
  ['strongestPair', 'strongest community pair', 'The community pair with the largest measured difference for this false friend.'],
  ['communityCode', 'community code', 'The CTT atlas code for the community.'],
  ['communityGroup', 'community group', 'The CTT atlas group the community belongs to.'],
  ['sourceBuild', 'source build', 'The CTT site build the import read.'],
];

/**
 * Renders a snapshot as a Turtle module. `includeExamples` keeps the published short
 * quotations (as skos:example with their attribution); the site already limits them.
 */
export function snapshotToTurtle(input, {base = DEFAULT_BASE, includeExamples = true} = {}) {
  const snapshot = validateSnapshot(input);
  assertBase(base);
  const c = name => `${CTT_PREFIX}:${name}`;
  const term = slug => iri(`${base}term/${slug}`);
  const community = code => iri(`${base}community/${code}`);
  const site = snapshot.source.site;
  const build = [snapshot.source.build.date, snapshot.source.build.commit].filter(Boolean).join(' ');
  const status = literal(snapshot.calibration, null);
  const lines = [
    `# CTT taxonomy terms imported from ${site} (${snapshot.source.kind}${build ? `, build ${build}` : ''}).`,
    `# Generated by scripts/ctt/import.mjs on ${snapshot.source.retrievedAt}. Calibration: ${snapshot.calibration}.`,
    `# Counts, labels and short quotations only; regenerate rather than editing by hand.`,
    ...Object.entries({...RDF_PREFIXES, [CTT_PREFIX]: base}).map(([p, ns]) => `@prefix ${p}: <${ns}> .`),
    '',
  ];
  for (const [name, label, comment] of ANNOTATIONS) {
    lines.push(`${c(name)} a owl:AnnotationProperty ;`, `    rdfs:label ${literal(label)} ;`, `    rdfs:comment ${literal(comment)} .`, '');
  }
  const note = snapshot.calibration === 'uncalibrated'
    ? 'Uncalibrated: no CTT verdict has been checked against human judgment yet. Treat each one as a hypothesis.'
    : 'Calibrated against human judgment by the CTT Taxonomy Working Group.';
  lines.push(
    `${c('Term')} a owl:Class ;`,
    `    rdfs:label ${literal('CTT term')} ;`,
    `    rdfs:comment ${literal(`A word measured by the CTT taxonomy atlas across ${snapshot.communities.length} communities. ${note}`)} ;`,
    `    ${c('calibrationStatus')} ${status} ;`,
    ...(build ? [`    ${c('sourceBuild')} ${literal(build, null)} ;`] : []),
    `    dcterms:source ${iri(site)} .`, '',
    `${c('FalseFriend')} a owl:Class ;`, `    rdfs:subClassOf ${c('Term')} ;`,
    `    rdfs:label ${literal('CTT false friend')} ;`,
    `    rdfs:comment ${literal('A word two communities mainly use in different senses, where each community\'s main sense is one the other barely uses.')} .`, '',
    `${c('CoreWord')} a owl:Class ;`, `    rdfs:subClassOf ${c('Term')} ;`,
    `    rdfs:label ${literal('CTT core word')} .`, '',
    `${c('Community')} a owl:Class ;`,
    `    rdfs:label ${literal('CTT community')} ;`,
    `    rdfs:comment ${literal('A community whose usage the CTT atlas measures.')} .`, '',
  );
  for (const item of snapshot.communities) {
    lines.push(`${community(item.code)} a owl:NamedIndividual, ${c('Community')} ;`,
      `    rdfs:label ${literal(item.label)} ;`,
      `    ${c('communityCode')} ${literal(item.code, null)} ;`,
      `    ${c('communityGroup')} ${literal(item.group)} .`, '');
  }
  for (const t of snapshot.terms) {
    const special = [...(t.verdict === 'false-friend' ? [c('FalseFriend')] : []), ...(t.core ? [c('CoreWord')] : [])];
    const parents = special.length ? special : [c('Term')];
    const props = [
      `rdfs:subClassOf ${parents.join(', ')}`,
      `rdfs:label ${literal(t.label)}`,
      `skos:prefLabel ${literal(t.label)}`,
      `${c('verdict')} ${literal(t.verdict, null)}`,
      `${c('calibrationStatus')} ${status}`,
      ...(t.senseCount === null ? [] : [`${c('senseCount')} ${integer(t.senseCount)}`]),
      ...(t.communityCount === null ? [] : [`${c('communityCount')} ${integer(t.communityCount)}`]),
      ...(t.useCount === null ? [] : [`${c('useCount')} ${integer(t.useCount)}`]),
      ...t.senses.map(s => `${c('senseSubstitutes')} ${literal(`${s.partOfSpeech ? `${s.partOfSpeech}: ` : ''}${s.substitutes.join(', ')}`)}`),
      ...(t.falseFriend ? [`${c('falseFriendPairCount')} ${integer(t.falseFriend.pairCount)}`, `${c('strongestPair')} ${literal(t.falseFriend.strongestPair.join(' / '))}`] : []),
      ...(includeExamples ? t.examples.map(e => `skos:example ${literal(`${e.quote} (${e.community} · ${e.work})`)}`) : []),
      `rdfs:seeAlso ${iri(`${site}vocabulary/#t-${t.slug}`)}`,
    ];
    lines.push(`${term(t.slug)} a owl:Class ;`, ...props.map((p, i) => `    ${p}${i === props.length - 1 ? ' .' : ' ;'}`), '');
  }
  return lines.join('\n');
}

/**
 * Appends a generated module to a host Turtle document. Turtle allows later @prefix
 * directives, so concatenation is valid as long as the module's prefixes do not
 * redefine one the host already binds to a different namespace (which would silently
 * change the meaning of the host's remaining triples if the order ever changed).
 */
export function mergeTurtle(host, module) {
  if (typeof host !== 'string' || typeof module !== 'string') throw new Error('Turtle merge needs two documents');
  const bindings = text => new Map([...text.matchAll(/^\s*@prefix\s+([A-Za-z][\w.-]*)?:\s*<([^>]*)>\s*\.\s*$/gm)].map(m => [m[1] ?? '', m[2]]));
  const hostPrefixes = bindings(host);
  for (const [prefix, ns] of bindings(module)) {
    if (hostPrefixes.has(prefix) && hostPrefixes.get(prefix) !== ns) throw new Error(`Turtle merge would rebind prefix "${prefix}:"`);
  }
  return `${host.replace(/\s*$/, '\n')}\n${module.replace(/\s*$/, '\n')}`;
}
